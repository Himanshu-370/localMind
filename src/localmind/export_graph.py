"""Project a LightRAG graph into a generated Obsidian vault (one note per entity)."""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import unicodedata
from pathlib import Path

SEP = "<SEP>"  # lightrag.constants.GRAPH_FIELD_SEP
MARKER = ".localmind-vault"
LEGACY_MARKER = "generated by LocalMind; safe to delete\n"
_BAD = re.compile(r'[\\/:*?"<>|#^\[\]\x00-\x1f]')


def safe_name(name: str) -> str:
    s = _BAD.sub(" ", name).strip(" .") or "unnamed"
    return re.sub(r"\s+", " ", s)[:100]


def _filename_key(name: str) -> str:
    return unicodedata.normalize("NFC", name).casefold()


def assign_filenames(names: list[str]) -> dict[str, str]:
    """Deterministic, collision-free note names (case-insensitive FS safe)."""
    out: dict[str, str] = {}
    used: set[str] = set()
    for n in sorted(names):
        base = safe_name(n)
        cand = base
        if _filename_key(cand) in used:
            digest = hashlib.sha1(n.encode()).hexdigest()[:6]
            cand = f"{base} ({digest})"
            suffix = 1
            while _filename_key(cand) in used:
                cand = f"{base} ({digest}-{suffix})"
                suffix += 1
        used.add(_filename_key(cand))
        out[n] = cand
    return out


def _sources(item: dict, doc_paths: dict[str, str]) -> list[str]:
    """Original paths via chunk ids ("<doc_id>-chunk-N"); LightRAG's own
    file_path is only a basename. Unmapped chunks are ignored."""
    ids = (p.rsplit("-chunk-", 1)[0] for p in (item.get("source_id") or "").split(SEP) if p)
    return sorted({doc_paths[i] for i in ids if i in doc_paths})


def _one_line(text: str | None) -> str:
    return " ".join((text or "").replace(SEP, " / ").split())


def export_vault(nodes: list[dict], edges: list[dict], vault: Path,
                 doc_paths: dict[str, str] | None = None) -> dict:
    """Write graph notes while preserving untracked and edited files."""
    doc_paths = doc_paths or {}
    vault.mkdir(parents=True, exist_ok=True)
    marker = vault / MARKER
    tracked = {}
    if marker.is_file() and not marker.is_symlink():
        contents = marker.read_text(encoding="utf-8")
        if contents != LEGACY_MARKER:
            tracked = json.loads(contents)
            if not isinstance(tracked, dict):
                raise ValueError(f"Invalid LocalMind note inventory in {marker}")
    elif any(vault.iterdir()):
        raise ValueError(f"{vault} is not an empty or generated vault; refusing to write")

    unchanged = set()
    for entry in vault.iterdir():
        digest = tracked.get(entry.name)
        if digest and entry.suffix == ".md" and not entry.is_symlink() and entry.is_file():
            if hashlib.sha256(entry.read_bytes()).hexdigest() == digest:
                unchanged.add(entry.name)

    ids = {n["id"] for n in nodes}
    files = assign_filenames(list(ids))
    out_e: dict[str, list[dict]] = {i: [] for i in ids}
    in_e: dict[str, list[dict]] = {i: [] for i in ids}
    for e in edges:
        if e["source"] in ids and e["target"] in ids and e["source"] != e["target"]:
            out_e[e["source"]].append(e)
            in_e[e["target"]].append(e)

    def link(name: str) -> str:
        filename = files[name]
        if filename == name or any(char in name for char in "|[]\r\n"):
            return f"[[{filename}]]"
        return f"[[{filename}|{name}]]"

    notes: dict[str, bytes] = {}
    for n in nodes:
        name = n["id"]
        lines = ["---", f"type: {_one_line(n.get('entity_type') or 'unknown')}", "---",
                 f"# {name}", "", _one_line(n.get("description")) or "_No description._", ""]
        rels = [(e, e["target"], "→") for e in sorted(out_e[name], key=lambda e: e["target"])]
        rels += [(e, e["source"], "←") for e in sorted(in_e[name], key=lambda e: e["source"])]
        if rels:
            lines.append("## Relationships")
            for e, other, arrow in rels:
                kw = _one_line(e.get("keywords"))
                desc = _one_line(e.get("description"))
                lines.append(f"- {arrow} {link(other)} ({kw}): {desc}" if kw else
                             f"- {arrow} {link(other)}: {desc}")
            lines.append("")
        src = _sources(n, doc_paths)
        for e, _, _ in rels:
            src = sorted(set(src) | set(_sources(e, doc_paths)))
        if src:
            lines.append("## Sources")
            lines += [f"- `{s}`" for s in src]
            lines.append("")
        notes[f"{files[name]}.md"] = "\n".join(lines).encode("utf-8")

    new_names = {_filename_key(name): name for name in notes}
    for entry in vault.iterdir():
        if entry.name in unchanged:
            continue
        name = new_names.get(_filename_key(entry.name))
        if name is None:
            continue
        if entry.name == name and not entry.is_symlink() and entry.is_file():
            if entry.read_bytes() == notes[name]:
                continue
        raise ValueError(f"Generated note conflicts with {entry.name}. Move or rename that note and refresh again.")

    for name in unchanged - notes.keys():
        (vault / name).unlink()
    for name, content in notes.items():
        (vault / name).write_bytes(content)
    marker.write_text(json.dumps({name: hashlib.sha256(content).hexdigest()
                                  for name, content in notes.items()}), encoding="utf-8")
    return {"notes": len(nodes), "edges": sum(len(v) for v in out_e.values())}


def broken_links(vault: Path) -> list[tuple[str, str]]:
    stems = {p.stem for p in vault.glob("*.md")}
    bad = []
    for p in vault.glob("*.md"):
        for m in re.findall(r"\[\[([^\]|]+)(?:\|[^\]]*)?\]\]", p.read_text(encoding="utf-8")):
            if m not in stems:
                bad.append((p.name, m))
    return bad


def _replace_dirs(*pairs: tuple[Path, Path]) -> None:
    """Roll back completed swaps if any artifact fails to publish."""
    backups = [(staged, final, final.with_name(final.name + ".old")) for staged, final in pairs]
    for _, _, old in backups:
        if old.exists() or old.is_symlink():
            raise RuntimeError(f"An earlier refresh left a backup at {old}. Resolve it before refreshing.")

    moved_old: list[tuple[Path, Path]] = []
    published: list[tuple[Path, Path]] = []
    try:
        for staged, final, old in backups:
            if final.exists():
                final.rename(old)
                moved_old.append((old, final))
            staged.rename(final)
            published.append((final, staged))
    except Exception:
        for final, staged in reversed(published):
            final.rename(staged)
        for old, final in reversed(moved_old):
            old.rename(final)
        raise
    for old, _ in moved_old:
        shutil.rmtree(old, ignore_errors=True)


def replace_dir(staged: Path, final: Path) -> None:
    _replace_dirs((staged, final))


def replace_build(stage: Path, storage: Path, stage_vault: Path, vault: Path) -> None:
    _replace_dirs((stage, storage), (stage_vault, vault))
